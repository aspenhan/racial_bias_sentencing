offense_type_of <- function(codesection) {
  lookup <- set_names(rep(names(offense_codes), lengths(offense_codes)), unlist(offense_codes))
  code <- str_remove(codesection, "^[A-Z][.](?=[0-9])")   # drop a leading "X." prefix
  coalesce(unname(lookup[code]), "other")
}
